-- 1. 테이블
create table clubs (
  id bigint generated by default as identity primary key,
  name text not null unique,
  payment_hours int not null default 48,         -- 입금 기한(시간)
  bank_name text,                                -- 입금 계좌(산악회별)
  bank_account text,
  bank_holder text
);
create table super_admins (                        -- 총괄 관리자
  user_id uuid primary key references auth.users(id) on delete cascade
);
create table club_admins (                         -- 산악회별 담당자
  user_id uuid references auth.users(id) on delete cascade,
  club_id bigint references clubs(id) on delete cascade,
  primary key (user_id, club_id)
);
create table trips (
  id bigint generated by default as identity primary key,
  club_id bigint not null references clubs(id) on delete cascade,
  title text not null,
  trip_date timestamptz not null,
  fee_regular int not null default 0 check (fee_regular >= 0),  -- 정회원 1인 회비(원)
  fee_guest int not null default 0 check (fee_guest >= 0)       -- 일일회원 1인 회비(원)
);
create table buses (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references trips(id) on delete cascade,
  bus_no int not null,
  seat_count int not null default 45 check (seat_count between 8 and 60),
  unique (trip_id, bus_no)
);
create table bus_seats (
  id bigint generated by default as identity primary key,
  bus_id bigint not null references buses(id) on delete cascade,
  seat_number int not null,
  row_number int not null,
  status text not null default 'available' check (status in ('available', 'locked', 'confirmed')),
  unique (bus_id, seat_number)
);
create table reservations (
  id bigint generated by default as identity primary key,
  bus_id bigint not null references buses(id) on delete cascade,
  main_user_name text not null,
  phone text not null,
  depositor_name text,
  headcount int not null check (headcount between 1 and 4),
  seat_numbers text not null,
  companion_names text,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'cancelled', 'expired')),
  expires_at timestamptz not null,
  amount int not null default 0,                 -- 신청 시점의 입금 금액(회원 구분별 회비 합계)
  member_types text not null default '',         -- 탑승자별 구분(regular/guest), 대표부터 순서대로
  created_at timestamptz not null default now()
);

-- 2. 권한 확인 함수
create or replace function is_super() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from super_admins where user_id = auth.uid()) $$;

create or replace function can_manage_club(p_club bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select is_super() or exists (select 1 from club_admins where user_id = auth.uid() and club_id = p_club) $$;

create or replace function bus_club_id(p_bus bigint) returns bigint
language sql stable security definer set search_path = public as $$
  select t.club_id from buses b join trips t on t.id = b.trip_id where b.id = p_bus $$;

-- 3. 자동 생성: 산행 등록 → 1호차 / 버스 등록 → 좌석 생성
--    좌석 수가 4로 나눠 1이 남는 차종(45, 41, 37…)은 맨 뒤 5석, 나머지는 열당 4석
create or replace function create_first_bus() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into buses (trip_id, bus_no) values (new.id, 1);
  return new;
end $$;
create trigger trips_first_bus after insert on trips for each row execute function create_first_bus();

create or replace function create_bus_seats() returns trigger
language plpgsql security definer set search_path = public as $$
declare i int;
begin
  for i in 1..new.seat_count loop
    insert into bus_seats (bus_id, seat_number, row_number) values (
      new.id, i,
      case when new.seat_count % 4 = 1 and i > new.seat_count - 5
           then (new.seat_count - 5) / 4 + 1 else (i - 1) / 4 + 1 end);
  end loop;
  return new;
end $$;
create trigger buses_create_seats after insert on buses for each row execute function create_bus_seats();

