create policy "본인 총괄 조회" on super_admins for select to authenticated using (user_id = auth.uid());

-- 5. 입금 기한이 지난 가배정 자동 해제 (좌석을 열거나 예약할 때마다 실행)
create or replace function release_expired_reservations() returns void
language plpgsql security definer set search_path = public as $$
begin
  with e as (
    update reservations set status = 'expired'
    where status = 'pending' and expires_at < now()
    returning bus_id, seat_numbers)
  update bus_seats s set status = 'available'
  from e where s.bus_id = e.bus_id
    and s.seat_number = any (string_to_array(e.seat_numbers, ',')::int[])
    and s.status = 'locked';
end $$;

-- 6. 예약 신청 (좌석 잠금 + 저장을 한 번에, 입금기한과 금액 반환)
--    p_types: 탑승자별 회원 구분('regular' 정회원 / 'guest' 일일회원), 좌석 수와 같아야 하며 첫 번째가 대표
create or replace function reserve_seats(
  p_bus_id bigint, p_name text, p_phone text, p_depositor text, p_companions text, p_seats int[], p_types text[]
) returns jsonb language plpgsql security definer set search_path = public as $$
declare v_count int; v_hours int; v_fr int; v_fg int; v_reg int; v_guest int; v_exp timestamptz; v_amt int;
begin
  perform release_expired_reservations();
  if coalesce(length(trim(p_name)), 0) = 0 then raise exception '대표 신청자 이름을 입력해주세요.'; end if;
  if length(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g')) < 9 then
    raise exception '연락처를 정확히 입력해주세요.'; end if;
  if array_length(p_seats, 1) is null or array_length(p_seats, 1) > 4 then
    raise exception '좌석은 1~4개까지 선택할 수 있습니다.'; end if;
  if array_length(p_types, 1) is distinct from array_length(p_seats, 1)
     or exists (select 1 from unnest(p_types) x where x not in ('regular', 'guest')) then
    raise exception '회원 구분(정회원/일일회원)을 확인해주세요.'; end if;

  update bus_seats set status = 'locked'
  where bus_id = p_bus_id and seat_number = any (p_seats) and status = 'available' and row_number > 2;
  get diagnostics v_count = row_count;
  if v_count <> array_length(p_seats, 1) then
    raise exception '이미 예약되었거나 선택할 수 없는 좌석이 있습니다. 좌석을 다시 선택해주세요.'; end if;

  select c.payment_hours, t.fee_regular, t.fee_guest into v_hours, v_fr, v_fg from buses b
    join trips t on t.id = b.trip_id join clubs c on c.id = t.club_id where b.id = p_bus_id;
  select count(*) filter (where x = 'regular'), count(*) filter (where x = 'guest') into v_reg, v_guest from unnest(p_types) x;
  v_exp := now() + make_interval(hours => v_hours);
  v_amt := v_reg * v_fr + v_guest * v_fg;

  insert into reservations (bus_id, main_user_name, phone, depositor_name, headcount, seat_numbers,
                            companion_names, expires_at, amount, member_types)
  values (p_bus_id, trim(p_name), trim(p_phone), nullif(trim(p_depositor), ''), array_length(p_seats, 1),
          array_to_string(p_seats, ','), nullif(trim(p_companions), ''), v_exp, v_amt, array_to_string(p_types, ','));
  return jsonb_build_object('expires_at', v_exp, 'amount', v_amt);
end $$;

-- 7. 담당자 전용: 입금 확정 / 예약 취소
create or replace function confirm_reservation(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare r reservations; a int[]; n int;
begin
  select * into r from reservations where id = p_id for update;
  if r.id is null then raise exception '없는 예약입니다.'; end if;
  if not can_manage_club(bus_club_id(r.bus_id)) then raise exception '권한이 없습니다.'; end if;
  if r.status in ('confirmed', 'cancelled') then raise exception '이미 처리된 예약입니다.'; end if;
  a := string_to_array(r.seat_numbers, ',')::int[];
  if r.status = 'expired' then   -- 기한이 지났어도 좌석이 비어 있으면 확정 가능
    update bus_seats set status = 'locked' where bus_id = r.bus_id and seat_number = any (a) and status = 'available';
    get diagnostics n = row_count;
    if n <> cardinality(a) then raise exception '기한이 지나 좌석이 이미 다른 사람에게 배정되었습니다.'; end if;
  end if;
  update bus_seats set status = 'confirmed' where bus_id = r.bus_id and seat_number = any (a);
  update reservations set status = 'confirmed' where id = p_id;
end $$;

create or replace function cancel_reservation(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare r reservations;
begin
  select * into r from reservations where id = p_id for update;
  if r.id is null then raise exception '없는 예약입니다.'; end if;
  if not can_manage_club(bus_club_id(r.bus_id)) then raise exception '권한이 없습니다.'; end if;
  if r.status not in ('pending', 'confirmed') then raise exception '이미 취소되었거나 기한이 만료된 예약입니다.'; end if;
  update reservations set status = 'cancelled' where id = p_id;
  update bus_seats set status = 'available'
  where bus_id = r.bus_id and seat_number = any (string_to_array(r.seat_numbers, ',')::int[]);
end $$;

-- 8. 버스 추가 (산행마다 기본 1대, 필요하면 담당자가 추가)
create or replace function add_bus(p_trip_id bigint, p_seat_count int default 45) returns int
language plpgsql security definer set search_path = public as $$
declare v_club bigint; v_no int;
begin
  select club_id into v_club from trips where id = p_trip_id;
  if v_club is null or not can_manage_club(v_club) then raise exception '권한이 없습니다.'; end if;
  select coalesce(max(bus_no), 0) + 1 into v_no from buses where trip_id = p_trip_id;
  insert into buses (trip_id, bus_no, seat_count) values (p_trip_id, v_no, p_seat_count);
  return v_no;
end $$;

-- 8-1. 산악회 정보(이름, 입금 기한, 입금 계좌) 수정: 해당 산악회 담당자 또는 총괄
create or replace function update_club(
  p_club_id bigint, p_name text, p_payment_hours int, p_bank_name text, p_bank_account text, p_bank_holder text
) returns void language plpgsql security definer set search_path = public as $$
begin
  if not can_manage_club(p_club_id) then raise exception '권한이 없습니다.'; end if;
  if coalesce(length(trim(p_name)), 0) = 0 then raise exception '산악회 이름을 입력해주세요.'; end if;
  update clubs set name = trim(p_name), payment_hours = greatest(coalesce(p_payment_hours, 48), 1),
    bank_name = nullif(trim(p_bank_name), ''), bank_account = nullif(trim(p_bank_account), ''),
    bank_holder = nullif(trim(p_bank_holder), '') where id = p_club_id;
end $$;

-- 9. 총괄 관리자 전용: 산악회별 담당자 지정
create or replace function my_access() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('super', is_super(),
    'clubs', coalesce((select jsonb_agg(club_id) from club_admins where user_id = auth.uid()), '[]'::jsonb)) $$;

create or replace function list_club_admins()
returns table (user_id uuid, email text, club_id bigint, club_name text)
language plpgsql security definer set search_path = public as $$
begin
  if not is_super() then raise exception '총괄 관리자만 사용할 수 있습니다.'; end if;
  return query select ca.user_id, u.email::text, ca.club_id, c.name
    from club_admins ca join auth.users u on u.id = ca.user_id join clubs c on c.id = ca.club_id
    order by c.name, u.email;
end $$;

create or replace function assign_club_admin(p_email text, p_club_id bigint) returns void
language plpgsql security definer set search_path = public as $$
declare v_uid uuid;
begin
  if not is_super() then raise exception '총괄 관리자만 사용할 수 있습니다.'; end if;
  select id into v_uid from auth.users where lower(email) = lower(trim(p_email));
  if v_uid is null then
    raise exception '해당 이메일 계정이 없습니다. Supabase Authentication > Users에서 먼저 계정을 만들어주세요.'; end if;
  insert into club_admins (user_id, club_id) values (v_uid, p_club_id) on conflict do nothing;
end $$;

create or replace function remove_club_admin(p_user_id uuid, p_club_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not is_super() then raise exception '총괄 관리자만 사용할 수 있습니다.'; end if;
  delete from club_admins where user_id = p_user_id and club_id = p_club_id;
end $$;

